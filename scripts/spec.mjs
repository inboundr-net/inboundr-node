// Keeps the SDK's types in step with the platform's API description.
//
//   npm run spec:sync    copy openapi.yaml from the platform, regenerate types
//   npm run spec:types   regenerate src/generated/api.ts from openapi/openapi.yaml
//   npm run spec:check   exit 1 if src/generated/api.ts is stale (run in CI)
//
// spec:sync reads INBOUNDR_SPEC (a path or an https URL), defaulting to a
// sibling checkout of the platform at ../inbound-app.
import { execFileSync } from "node:child_process";
import { createRequire } from "node:module";
import { copyFileSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const SPEC = join(root, "openapi/openapi.yaml");
const TYPES = join(root, "src/generated/api.ts");
const HEADER =
  "// GENERATED by `npm run spec:types` from openapi/openapi.yaml. Do not edit.\n\n";

// The generator's own entry script, run with this Node. Calling
// node_modules/.bin/openapi-typescript directly works only on POSIX, where the
// bin is a symlink; on Windows it's a .cmd shim that execFile can't start.
const require = createRequire(import.meta.url);
const generatorPkg = require.resolve("openapi-typescript/package.json");
const { bin } = JSON.parse(readFileSync(generatorPkg, "utf8"));
const GENERATOR = join(generatorPkg, "..", typeof bin === "string" ? bin : bin["openapi-typescript"]);

function generate(out) {
  execFileSync(
    process.execPath,
    [GENERATOR, SPEC, "-o", out, "--default-non-nullable=false"],
    { stdio: ["ignore", "ignore", "inherit"] },
  );
  writeFileSync(out, HEADER + readFileSync(out, "utf8"));
}

async function sync() {
  const source = process.env.INBOUNDR_SPEC ?? join(root, "../inbound-app/openapi/openapi.yaml");
  if (/^https?:\/\//.test(source)) {
    const res = await fetch(source);
    if (!res.ok) throw new Error(`GET ${source}: ${res.status}`);
    writeFileSync(SPEC, await res.text());
  } else {
    copyFileSync(source, SPEC);
  }
  console.log(`spec: copied ${source}`);
  generate(TYPES);
  console.log("spec: regenerated src/generated/api.ts");
}

function check() {
  const dir = mkdtempSync(join(tmpdir(), "inboundr-spec-"));
  try {
    const out = join(dir, "api.ts");
    generate(out);
    if (readFileSync(out, "utf8") !== readFileSync(TYPES, "utf8")) {
      console.error("src/generated/api.ts is stale. Run `npm run spec:types`.");
      // exitCode, not exit(): exit() would skip the cleanup below.
      process.exitCode = 1;
      return;
    }
    console.log("spec: generated types are up to date");
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

const mode = process.argv[2];
if (mode === "sync") await sync();
else if (mode === "types") generate(TYPES);
else if (mode === "check") check();
else {
  console.error("usage: node scripts/spec.mjs sync|types|check");
  process.exit(2);
}
